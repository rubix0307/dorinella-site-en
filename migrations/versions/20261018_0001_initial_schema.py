# One generic function for every tracked table (see app/audit.py): the actor comes from the transaction setting `app.actor`
# ('user:<id>' / 'system:<job>'); the columns named as trigger arguments are left out of the logged row.
AUDIT_FUNCTION = r"""
CREATE OR REPLACE FUNCTION audit_row() RETURNS trigger AS $$
DECLARE
    src jsonb := COALESCE(to_jsonb(NEW), to_jsonb(OLD));
    old_row jsonb;
    new_row jsonb;
    rid text;
    n integer;
    who text := COALESCE(NULLIF(current_setting('app.actor', true), ''), 'db:' || session_user);
BEGIN
    IF TG_OP <> 'INSERT' THEN
        old_row := to_jsonb(OLD);
    END IF;
    IF TG_OP <> 'DELETE' THEN
        new_row := src;
    END IF;
    FOR n IN 0 .. TG_NARGS - 1 LOOP
        old_row := old_row - TG_ARGV[n];
        new_row := new_row - TG_ARGV[n];
    END LOOP;
    IF TG_OP = 'UPDATE' AND old_row = new_row THEN
        RETURN NULL;                                       -- nothing that is logged changed: nothing to record
    END IF;
    -- the id of the row: its primary key (parts joined by ':')
    SELECT string_agg(src ->> a.attname, ':' ORDER BY k.ord) INTO rid
      FROM pg_index x
      CROSS JOIN LATERAL unnest(x.indkey) WITH ORDINALITY AS k(attnum, ord)
      JOIN pg_attribute a ON a.attrelid = x.indrelid AND a.attnum = k.attnum
     WHERE x.indrelid = TG_RELID AND x.indisprimary;
    IF rid IS NULL THEN
        RAISE EXCEPTION 'audit_row: table % has no primary key', TG_TABLE_NAME;
    END IF;
    INSERT INTO audit_log (txid, table_name, row_id, op, old_data, new_data, actor, actor_id, db_user)
    VALUES (txid_current(), TG_TABLE_NAME, rid, TG_OP, old_row, new_row, who,
            CASE WHEN who LIKE 'user:%' THEN substr(who, 6)::integer END, session_user);
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;
"""

# audit_log refuses UPDATE / DELETE / TRUNCATE unless the transaction says app.audit_purge = 'on'
AUDIT_GUARD = r"""
CREATE FUNCTION audit_log_guard() RETURNS trigger AS $$
BEGIN
    IF current_setting('app.audit_purge', true) = 'on' THEN
        IF TG_OP = 'TRUNCATE' THEN
            RETURN NULL;
        END IF;
        RETURN CASE TG_OP WHEN 'DELETE' THEN OLD ELSE NEW END;
    END IF;
    RAISE EXCEPTION 'audit_log is append-only (% refused)', TG_OP USING ERRCODE = 'insufficient_privilege';
END;
$$ LANGUAGE plpgsql;
"""


