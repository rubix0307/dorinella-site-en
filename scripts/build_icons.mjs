// Icons that change state in place: they morph instead of swapping (see app/static/js/morph.js).
const MORPH = [
    'armchair', 'arrow-right', 'arrow-up-down', 'calendar', 'check', 'chevron-down', 'chevron-up', 'chevrons-up-down', 'copy',
    'ellipsis', 'eye', 'eye-off', 'list-filter', 'menu', 'minus', 'plus', 'search', 'trash', 'x',
];
// Morph states Lucide has no icon for, drawn here from a Lucide one.
const CUSTOM = {
    // trash with its lid tilted up (Lucide trash: lid and handle turned 12° about the lid's left end)
    'trash-open': [['path', {d: 'M19 6v14a2 2 0 0 1-2 2H7a2 2 0 0 1-2-2V6'}], ['path', {d: 'M3 6.8 20.6 3.06'}],
                   ['path', {d: 'M7.89 5.76 7.47 3.8a2 2 0 0 1 1.55-2.37l3.91-.83a2 2 0 0 1 2.37 1.54l.41 1.96'}]],
};
// Brand icons left Lucide in v1; kept from the previous sprite.
const KEEP = ['instagram'];

const pascal = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const node = (name) => {
    const data = icons[pascal(name)];
    if (!data) throw new Error(`no Lucide icon "${name}"`);
    return data;
};
const attrs = (a) => Object.entries(a).map(([k, v]) => ` ${k}="${v}"`).join('');

const spritePath = join(ROOT, 'app/templates/includes/icons.html');
const previous = readFileSync(spritePath, 'utf8');
const kept = KEEP.map((name) => {
    const match = previous.match(new RegExp(`\\s*<symbol id="i-${name}"[\\s\\S]*?</symbol>`));
    if (!match) throw new Error(`missing kept icon ${name}`);
    return match[0].trimStart();
});
const symbols = STATIC.map((name) =>
    `<symbol id="i-${name}" viewBox="0 0 24 24">${node(name).map(([tag, a]) => `<${tag}${attrs(a)}/>`).join('')}</symbol>`);
writeFileSync(spritePath, [
    '{# Generated by scripts/build_icons.mjs from the lucide package (https://lucide.dev, ISC). Do not edit by hand. #}',
    '{# Use icon(\'name\') for static icons and micon(\'name\') for icons that morph (morphicons). #}',
    '<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">',
    ...[...symbols, ...kept].map((s) => `    ${s}`),
    '</svg>',
    '',
].join('\n'));

const morph = Object.fromEntries([...MORPH.map((name) => [name, canonicalD(node(name))]),
                                  ...Object.entries(CUSTOM).map(([name, nodes]) => [name, canonicalD(nodes)])]);
writeFileSync(join(ROOT, 'app/core/morph_icons.json'), `${JSON.stringify(morph, null, 2)}\n`);
writeFileSync(join(ROOT, 'app/static/js/morph-icons.js'),
    `// Generated by scripts/build_icons.mjs: Lucide path data normalized for morphicons. Do not edit by hand.\n` +
    `export default ${JSON.stringify(morph, null, 4)};\n`);
console.log(`sprite: ${symbols.length + kept.length} icons, morph: ${MORPH.length} icons`);
