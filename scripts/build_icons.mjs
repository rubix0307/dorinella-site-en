// Builds every icon asset from the real packages, so nothing is hand-copied:
//   * app/templates/includes/icons.html  — Lucide (https://lucide.dev) SVG sprite for static icons
//   * app/static/js/morph-icons.js       — path data for animated icons (morphicons, https://www.morphicons.com)
//   * app/core/morph_icons.json          — the same path data for the server-side `micon()` macro
//
// Run:  npm i --no-save --prefix .icon-build lucide@1.8.0 morphicons@1.7.1
//       node scripts/build_icons.mjs .icon-build
import {readFileSync, writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {join, resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

const ROOT = resolve(import.meta.dirname, '..');
const deps = resolve(process.argv[2] || '.icon-build');
const require = createRequire(join(deps, 'node_modules', 'x.js'));
const {icons} = require('lucide');
const {canonicalD} = await import(pathToFileURL(join(deps, 'node_modules/morphicons/dist/dom.js')).href);

// Static icons used by the templates (icon('name')).
